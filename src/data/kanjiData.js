export const getKanjiByBabs = (babList = []) => {
  const babSet = new Set(babList);
  return kanjiData
    .filter((b) => babSet.has(b.bab))
    .flatMap((b) => b.list.map((item) => ({ ...item, bab: b.bab })));
};
export const shuffleArray = (arr) => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

/**
 * Membuat soal kuis dari data kanji.
 *
 * @param {Object} opts
 * @param {number[]} opts.babList      - daftar nomor bab yang dipilih, mis. [1,2,3]
 * @param {"kanji"|"hiragana"|"arti"} opts.questionType - field yang ditampilkan sbg soal
 * @param {"kanji"|"hiragana"|"arti"} opts.answerType   - field yang ditampilkan sbg pilihan jawaban
 * @param {number} [opts.jumlahSoal]   - jumlah soal (default: semua kanji dari bab terpilih)
 * @param {number} [opts.jumlahPilihan=4] - jumlah opsi pilihan ganda per soal
 * @returns {Array<{ question: string, options: string[], correctAnswer: string, kanji: string, hiragana: string, arti: string, bab: number }>}
 */
export const generateQuiz = ({
  babList = [],
  questionType = "kanji",
  answerType = "arti",
  jumlahSoal,
  jumlahPilihan = 4,
}) => {
  const pool = getKanjiByBabs(babList);
  if (pool.length === 0) return [];

  const jumlah = jumlahSoal ? Math.min(jumlahSoal, pool.length) : pool.length;
  const selected = shuffleArray(pool).slice(0, jumlah);

  return selected.map((item) => {
    const distractorPool = pool.filter((p) => p[answerType] !== item[answerType]);
    const distractors = shuffleArray(distractorPool)
      .slice(0, Math.max(jumlahPilihan - 1, 0))
      .map((p) => p[answerType]);

    const options = shuffleArray([item[answerType], ...distractors]);

    return {
      question: item[questionType],
      options,
      correctAnswer: item[answerType],
      kanji: item.kanji,
      hiragana: item.hiragana,
      arti: item.arti,
      bab: item.bab,
    };
  });
};

