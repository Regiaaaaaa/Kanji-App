export const getBabNumbers = () => kanjiData.map((b) => b.bab);

export const normalizeAnswerValue = (value = "") =>
  String(value)
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[~～]/g, "")
    .replace(/[-–—_]/g, " ")
    .replace(/[.,!?;:()[\]{}]/g, "")
    .replace(/\u2026/g, "")
    .replace(/\s+/g, " ")
    .trim();

export const getAnswerVariants = (value = "") => {
  const raw = String(value ?? "").trim();
  if (!raw) return [];

  const variants = new Set();
  const parts = raw.split("/");

  parts.forEach((part) => {
    const normalized = normalizeAnswerValue(part);
    if (normalized) variants.add(normalized);
  });

  const base = normalizeAnswerValue(raw);
  if (base) variants.add(base);

  return [...variants];
};

export const getKanjiByBabs = (babList = []) => {
  const babSet = new Set(babList);
  return kanjiData
    .filter((b) => babSet.has(b.bab))
    .flatMap((b) => b.list.map((item) => ({ ...item, bab: b.bab })));
};
export const shuffleArray = (arr) => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

/**
 * 
 *
 * @param {Object} opts
 * @param {number[]} opts.babList      
 * @param {"kanji"|"hiragana"|"arti"} opts.questionType
 * @param {"kanji"|"hiragana"|"arti"} opts.answerType   
 * @param {number} [opts.jumlahSoal]   
 * @param {number} [opts.jumlahPilihan=4] 
 * @returns {Array<{ question: string, options: string[], correctAnswer: string, kanji: string, hiragana: string, arti: string, bab: number }>}
 */
export const generateQuiz = ({
  babList = [],
  questionType = "kanji",
  answerType = "arti",
  jumlahSoal,
  jumlahPilihan = 4,
}) => {
  const pool = getKanjiByBabs(babList);
  if (pool.length === 0) return [];

  const jumlah = jumlahSoal ? Math.min(jumlahSoal, pool.length) : pool.length;
  const selected = shuffleArray(pool).slice(0, jumlah);

  return selected.map((item) => {
    const correctVariants = new Set(getAnswerVariants(item[answerType]));
    const distractorPool = pool.filter((p) => {
      const candidateVariants = getAnswerVariants(p[answerType]);
      return !candidateVariants.some((variant) => correctVariants.has(variant));
    });

    const distractors = shuffleArray(distractorPool)
      .slice(0, Math.max(jumlahPilihan - 1, 0))
      .map((p) => p[answerType]);

    const options = shuffleArray([item[answerType], ...distractors]);

    return {
      question: item[questionType],
      options,
      correctAnswer: item[answerType],
      kanji: item.kanji,
      hiragana: item.hiragana,
      arti: item.arti,
      bab: item.bab,
    };
  });
};

